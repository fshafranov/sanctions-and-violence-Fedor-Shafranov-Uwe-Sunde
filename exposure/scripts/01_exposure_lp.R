# =============================================================================
# 01_exposure_lp.R — do sanctions bite harder where the target depends on the sender?
#
# Added 2026-11-09 (exposure/ANALYSIS_PLAN.md, E3, E4, E8). Panel local projections as in
# empirics/scripts/13_local_projections.R (levels, shock second, state + year FE, 2 lags of shock and response,
# SE clustered by state), with the shock interacted with the target's pre-sanction exposure to the sender:
#
#   y_i,t+h = b_h x_it + c_h x_it * Z_it [+ d_h Z_it] + sum_k (lags of x, y) + y_it + state FE + year FE + e
#
#   x = number of new cases in t (US without ICC case 685 / EU / all cases without 685)
#   Z = standardised exposure to the matching sender group, mean over t-3..t-1 (data/README.md 4c, X4):
#       US shock -> US; EU shock -> EU members of the year; all cases -> the actual senders of the year's new
#       cases (only in shock years: no main effect d_h, Z = 0 where x = 0)
#   Exposure measures: trade with sender / GDP as log(1 + %) and winsorised at p99 (user 9 Nov), sender share of
#       trade, sender share of arms imports. Standardised over the shock state-years: b_h = response at average
#       exposure, c_h = additional response per 1 SD more exposure.
# Outcomes: UCDP, ACLED, GDELT (user 9 Nov: figures for all three), each in its own window
#       (functions_exposure.R, build_source_panel()).
# Output: exposure/results/tables/exposure_lp.csv, exposure_lp.md;
#         figures fig_e1_exposure_lp_<source>.png (paths h = 1..8, per year)
# =============================================================================
source(here::here("exposure", "scripts", "00_setup.R"))
source(here::here("exposure", "scripts", "functions_exposure.R"))

results <- list()
for (source in names(SOURCES)) {
  d <- exposure_data(source)
  for (shock_name in names(SHOCKS)) for (measure in names(MEASURES))
    results[[length(results) + 1]] <- estimate_paths(d, source, shock_name, measure)
}
results <- add_labels(bind_rows(results))
write_csv(results, file.path(TABLES, "exposure_lp.csv"))

# --- figures: one per source, paths h = 1..8 -------------------------------------------------------------
term_colours <- c("shock (at mean exposure)" = "#52514e", "shock x exposure (per SD)" = PAPER_COLOURS[["blue"]])
for (source in names(SOURCES)) {
  fig <- ggplot(results %>% filter(source == !!source, type == "per year"),
                aes(horizon, estimate, colour = term, fill = term)) +
    geom_hline(yintercept = 0, colour = "#52514e", linewidth = 0.3) +
    geom_ribbon(aes(ymin = lower, ymax = upper), alpha = 0.12, colour = NA) +
    geom_line(linewidth = 0.7) + geom_point(size = 1) +
    facet_grid(measure_label ~ shock_label, scales = "free_y", labeller = label_wrap_gen(width = 22)) +
    scale_colour_manual(values = term_colours) + scale_fill_manual(values = term_colours) +
    scale_x_continuous(breaks = 1:HORIZON) +
    labs(title = paste0("Violence after a new sanction, by the target's exposure to the sender — ", SOURCES[[source]]),
         x = "Years after the sanction (h)", y = paste0("Response of ", SOURCE_UNITS[[source]], " in t + h"),
         colour = NULL, fill = NULL,
         caption = paste0("Panel local projections, shock second, state and year FE, ", VAR_LAGS, " lags; 95% bands, ",
                          "SE clustered by state. Exposure: mean t-3..t-1, standardised over sanctioned state-years.\n",
                          "Grey: response at mean exposure; blue: additional response per 1 SD more exposure. ",
                          "All cases: exposure to the actual senders of the year's new cases. ",
                          "Window: ", SOURCES[[source]], " coverage.")) +
    theme_paper()
  save_figure(fig, paste0("fig_e1_exposure_lp_", source, ".png"), 12, 11)
}

# --- markdown: h = 2 per year and cumulative h = 0..3 -------------------------------------------------------
summary_rows <- results %>%
  filter((type == "per year" & horizon == 2) | (type == "cumulative" & horizon == 3)) %>%
  mutate(point = ifelse(type == "per year", "per year h = 2", "cumulative h = 0..3"),
         cell = paste0(format_cell(estimate, se, p_value), " [", shock_years, "]")) %>%
  select(source = source_label, shock = shock_label, exposure = measure_label, term, point, cell) %>%
  pivot_wider(names_from = point, values_from = cell) %>%
  arrange(source, shock, exposure, term)
writeLines(c(
  "# Sanction response by exposure to the sender", "",
  paste0("Generated by `exposure/scripts/01_exposure_lp.R` on ", format(Sys.time(), "%Y-%m-%d %H:%M"),
         ". Figures `fig_e1_exposure_lp_<source>.png`; all horizons in `exposure_lp.csv`."), "",
  "Local projections (shock second, state + year FE, 2 lags). *shock (at mean exposure)*: response for a sanctioned ",
  "target with average exposure; *shock x exposure*: additional response per 1 SD more pre-sanction exposure ",
  "(t-3..t-1) to the sender. Outcomes: UCDP log deaths per 100k, ACLED log fatalities per 100k, GDELT violent events ",
  "per 10,000 events. Cells: coefficient (SE) [shock state-years].", "",
  to_markdown(summary_rows),
  "*Notes:* * p<0.1, ** p<0.05, *** p<0.01."
), file.path(TABLES, "exposure_lp.md"))
cat("\nWrote", file.path(TABLES, "exposure_lp.md"), "\n")
